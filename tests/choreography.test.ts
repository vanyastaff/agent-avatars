test('all five personalities interpret the same delivered-message event differently', async ($, on) => {
  const clock = mock.clock(on, { now: 100000 })
  let serial = 0
  on('agent.spawn', () => ({ model: 'haiku', agentId: `child-${++serial}` }))
  on('session.send', () => ({ isDelivered: true }))
  const ui = await $.ui.mount(BAND)
  for (let i = 1; i <= 4; i++) await $.agent.spawn({ name: `Worker ${i}`, description: 'Work', prompt: 'Work' })
  await clock.advance(6000)
  for (const [agentId, gesture] of [
    [undefined, 'passes a neatly folded note'], ['child-1', 'opens a box of clues'],
    ['child-2', 'unfurls the note with a flourish'], ['child-3', 'offers the note with a yawn'], ['child-4', 'slides the note over gently'],
  ] as const) {
    await $.session.send({ agentId, to: agentId ? 'main' : 'child-1', text: 'same private contents' })
    await clock.advance(1500)
    await ui.redraw()
    const svg = await ui.find({ type: 'Svg' })
    expect(String(svg?.props.alt).includes(gesture)).toBe(true)
    expect((String(svg?.props.source).match(/Together:/g) ?? []).length).toBe(2)
    expect(String(svg?.props.source).includes('same private contents')).toBe(false)
    await clock.advance(5000)
  }
  await ui.unmount()
})

