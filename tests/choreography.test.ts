import { expect, mock, test } from 'claude-code/testing'
import { heldTools } from './host.ts'

const BAND = { plugin: 'agent-avatars', component: 'AbovePrompt', surface: 'desktop', props: { isWorking: true, bodyColumns: 95 } } as const

test('a real read progresses from fetching to studying and only packs up after the tool returns', async ($, on) => {
  const clock = mock.clock(on, { now: 100000 })
  on('agent.list', () => ({ value: [] }))
  on('config.list', () => ({ value: [] }))
  on('command.register', () => ({ value: undefined }))
  on('session.start', () => ({ cwd: '/work' }))
  const start = heldTools($, on, clock)
  await $.session.start({ surface: 'desktop', isInteractive: true, cwd: '/work' })
  const finish = await start({ tool: 'Read', file_path: '/work/a.rs' })
  const ui = await $.ui.mount(BAND)
  const source = async () => String((await ui.find({ type: 'Svg' }))?.props.source)
  expect(await source()).toContain('Action: selecting a reference')
  await clock.advance(1000)
  expect(await source()).toContain('Action: studying the pages')
  await clock.advance(1500)
  expect(await source()).toContain('Action: noting the reference')
  await clock.advance(8000)
  expect(await source()).not.toContain('Action: returning the reference')
  await finish()
  expect(await source()).toContain('Action: returning the reference')
  expect(await source()).toContain('thinking…')
  await clock.advance(2500)
  expect(await source()).not.toContain('Action: returning the reference')
  await ui.unmount()
})

test('a delivered message stages a personality-led handoff and new real work interrupts both actors', async ($, on) => {
  const clock = mock.clock(on, { now: 100000 })
  const start = heldTools($, on, clock)
  on('agent.spawn', () => ({ model: 'haiku', agentId: 'child' }))
  on('session.send', () => ({ isDelivered: true }))
  await $.agent.spawn({ name: 'Ada', description: 'Research', prompt: 'Work' })
  await clock.advance(6000)
  const ui = await $.ui.mount(BAND)
  await $.session.send({ to: 'child', text: 'private contents stay private' })
  const source = async () => String((await ui.find({ type: 'Svg' }))?.props.source)
  expect(await source()).toContain('Together: message handoff')
  await clock.advance(1500)
  await ui.redraw(BAND.props)
  expect(await source()).toContain('passes a neatly folded note')
  expect(await source()).toContain('checks both sides of the note')
  expect(await source()).not.toContain('private contents')
  const finish = await start({ tool: 'Read', agentId: 'child', file_path: '/work/a.rs' })
  expect(await source()).not.toContain('Together:')
  expect(await source()).toContain('Action: selecting a reference')
  await finish()
  await ui.unmount()
})

